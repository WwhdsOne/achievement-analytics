"""WWH 第 5 项 · 可调参数（唯一调参入口）

**改这里的值就够了**，不用翻逻辑代码。改完重跑：

    uv run python result/WWH/5/run.py analyze

``analyze`` 只读本地 SQLite、**不发任何 API 请求、不花钱**，所以下面这些门槛可以随便试。
报告和图表里的措辞会直接跟着变（它们从本模块读，没有另写字面量）。

每个参数都注明：默认值 / 管什么 / **调大调小会怎样** / 实测依据。

下面所有「实测」数字来自 2026-10-13 的全量标注结果（1000 款样本、982 款完成标注），
用生产代码逐个开关单独测出来的：

    组合                                   可用曲线   可配对
    A. 旧口径（四项全部收紧）                    8        8
    B. 当前默认  ← 你现在在这里                198      183
    C. 只把 STORY_CONF_MIN 降到 0.5            222      206
    D. 只把 ALLOW_MULTI_ENDING 改回 False      160      150
    E. 只把 REQUIRE_START_CHAIN 改回 True       15       14
    F. 只把 CURVE_BASELINE 改回 "start"        182      168

（A 是 8 而不是旧代码的 7：新实现不再要求「恰好一个 end 节点」，差 1 款。）
"""

# ═══════════════════════════════════════════════════════════════════════════
# 一、主线曲线 —— 改动这几个最影响可用样本量
# ═══════════════════════════════════════════════════════════════════════════

# 模型自报置信度的门槛（0~1）。低于它的游戏整条曲线不进分析。
#   调高（如 0.8）→ 只留模型很有把握的，但样本骤减
#   调低（如 0.5）→ 样本略增：实测 0.6 → 0.5 只从 198 涨到 222（+24），边际不大
# 为什么是 0.6：模型给出的主线整体置信度**中位数只有 0.7**，所以 0.8 等于系统性砍掉
# 一半以上样本（585/982 款倒在门槛上）。0.6 是「只保留模型觉得有把握的结果」
# 与「样本回到可用量级」的折中。
STORY_CONF_MIN = 0.6

# 允许多结局游戏进入分析。
#   True  → 模型判定「没有唯一结局」时，取完成率**最高**的那个结局作分子，
#           含义是「**至少**走到某个结局」的**下界**；**绝不相加**
#           （多个结局的解锁者可能重叠，相加会超过 100%）
#   False → 恢复旧口径，要求 unified_ending=true
# 为什么默认 True：很多游戏**有结局，只是不止一个**（多结局 RPG、分章节战役）。
# 旧口径把「没有统一结局」和「根本没有结局」混成一个 false 全丢掉。
# 实测：单独改回 False → 198 掉到 160（−38 款）。
ALLOW_MULTI_ENDING = True

# 归一化基准（分母）：
#   "highest" → 该游戏**完成率最高的成就**（≈「玩过这款游戏的人」）
#   "start"   → 模型指定的入门节点（旧口径）
# 指标读法随它变：
#   "highest" → 走到结局的人 ÷ **玩过这款游戏的人**
#   "start"   → 走到结局的人 ÷ **走到入门节点的人**
# 为什么默认 "highest"：不再依赖模型对 start 的判断，含义更直观。
# 实测：单独改回 "start" → 198 掉到 182（−16 款）；而且两种口径下「入门」那一点
# 通常都是 100%（模型标的入门节点基本就是完成率最高的成就），所以数值含义差别不大，
# 主要是稳健性提升。
CURVE_BASELINE = "start"

# 要求「后续节点必然要求经过入门节点」。
#   True  → 旧口径；模型要对**每个节点**单独回答 requires_start
#   False → 只信模型给出的阶段排序（节点仍须是 main + 本体 + 非联机 + 置信度达标）
# 为什么默认 False：该字段过于严苛，且叠在「已判为 main」之后属于**双重门禁**。
# 实测：**这是最大的单一闸门** —— 单独改回 True，198 直接掉到 15（−183 款）。
REQUIRE_START_CHAIN = False

# 一条曲线至少要有的公共主线节点数（含结局节点）。
#   调高 → 曲线更完整，但样本变少；调到 3 以上会明显掉
#   调到 1 → 「曲线」退化成两个点，没有意义
MIN_COMMON_CHECKPOINTS = 2

# ═══════════════════════════════════════════════════════════════════════════
# 二、RAWG 跨平台配对
# ═══════════════════════════════════════════════════════════════════════════

# 主指标 beaten/(beaten+dropped) 的最低分母。低于它的游戏不算配对。
#   调高 → 比例更稳（样本量大），但配对游戏数变少
#   调低 → 配对更多，但小分母噪声大（分母 1 时不是 0 就是 1）
# ⚠️ 必须出现在 RAWG_THRESHOLDS 里（主指标与敏感性分析要对得上）。
RAWG_MIN_DENOMINATOR = 20

# 报告里做敏感性分析的一组门槛（必须包含 RAWG_MIN_DENOMINATOR）。
# 实测：Spearman 对门槛很稳健——≥10 得 0.651、≥20 得 0.645、≥50 得 0.626。
# 三档一致说明这个相关不是被少数小样本游戏撑起来的。
RAWG_THRESHOLDS = (10, 20, 50)

# 是否同时报四状态口径（分母含 playing + owned，作为敏感性分析）。
# owned 不能证明实际玩过，所以只作补充，不作主指标。
RAWG_FOUR_STATUS = True

# ═══════════════════════════════════════════════════════════════════════════
# 三、统计与复现
# ═══════════════════════════════════════════════════════════════════════════

# Bootstrap 重抽样次数（游戏层）。调高更平滑但更慢；2000 已足够稳。
# 也可用命令行临时覆盖：--bootstrap-samples 500
BOOTSTRAP_SAMPLES = 2000

# 所有随机过程的种子。**改动它会让区间与之前不可比**，一般不要动。
RANDOM_STATE = 42

# ═══════════════════════════════════════════════════════════════════════════
# 四、标注调用（跑 label 时生效；这些会花钱，改前想清楚）
# ═══════════════════════════════════════════════════════════════════════════

# 每次请求带多少个成就。
#   调大 → 请求数变少，但单次输出更长、更容易被截断（表现为 finish_reason != "stop" 后重试）
#   调小 → 更稳但更慢更贵
# 可用 --batch-size 覆盖。
# ⚠️ 改动它会让 active_annotation 与实际入库的标注不匹配，续跑时程序会报错要求换库。
LABEL_BATCH_SIZE = 40

# 并行处理的**游戏数**（不是并发请求数的硬上限，重试会让瞬时请求数略高）。
#   调高 → 更快，但更容易撞 429 限流（会按 Retry-After 等待重试，不丢数据）
#   调到 1 → 完全串行（改造前的行为）
# 实测：3 路时 10 次请求 34 秒跑完；单次请求约 10~13 秒。可用 --workers 覆盖。
LABEL_WORKERS = 4

# 单个请求最多尝试几次（含首次）。都失败就记 error，该游戏下次可重跑、不丢数据。
# ⚠️ **内容校验失败也会重试**，而 temperature=0 下三次基本同错——
# 实测有一次 3 次尝试白烧约 1.1 万 completion token。降到 1 能省钱但要接受偶发失败。
MAX_ATTEMPTS = 3

# 重试退避：第 n 次尝试前等 RETRY_BACKOFF_BASE ** n 秒（默认 3 次尝试即 2s / 4s）。
RETRY_BACKOFF_BASE = 2

# 尊重响应头 Retry-After 时的等待上限（秒），避免被要求等几十分钟。
RETRY_MAX_WAIT_SEC = 60

# 单次响应的 token 上限。调小可能截断长批次（表现为 finish_reason != "stop" 后重试）。
MAX_TOKENS = 12000

# 采样温度。0 = 尽量确定，但**不保证**再次调用结果完全相同，
# 所以成功响应必须落库复用而不是重算（见 deepseek.py 的 input_hash 去重）。
TEMPERATURE = 0
